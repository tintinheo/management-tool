    namespace = "com.myguitarplayer"
    compileSdk = 37

    defaultConfig {
        applicationId = "com.myguitarplayer"
        minSdk = 31
        targetSdk = 36
        versionCode = 10
        versionName = "1.0.0"
    }

    signingConfigs {
        // Release key lives in keystore/ (gitignored). Falls back to the debug key so a release
        // build always installs; keep using the same key afterwards so updates keep progress.
        create("release") {
            val key = rootProject.file("keystore/myguitarplayer.keystore")
            storeFile = if (key.exists()) key else file(System.getProperty("user.home") + "/.android/debug.keystore")
            storePassword = "android"
            keyAlias = "androiddebugkey"
            keyPassword = "android"
        }
    }

    buildTypes {
        release {
            // R8 drops the unused part of material-icons-extended etc.: ~67 MB debug → a few MB.
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = signingConfigs.getByName("release")
        }
    }

    sourceSets {
        // src/main/java is shared with the Windows build (desktop/); Android-only code lives here.
        getByName("main") { kotlin.directories.add("src/main/androidOnly") }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
    }

    testOptions {
        unitTests {
            isIncludeAndroidResources = true
            all {
                it.jvmArgs(
                    "--add-exports=java.base/jdk.internal.access=ALL-UNNAMED",
                    "--add-opens=java.base/jdk.internal.access=ALL-UNNAMED",
                    "--add-opens=java.base/java.io=ALL-UNNAMED",
                )
            }
        }
    }
}

